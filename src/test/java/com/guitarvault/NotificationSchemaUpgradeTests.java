package com.guitarvault;

import java.sql.DriverManager;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.mail.javamail.JavaMailSender;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;
import org.springframework.test.context.bean.override.mockito.MockitoBean;
import org.springframework.transaction.annotation.Transactional;
import static org.assertj.core.api.Assertions.assertThat;

/** Exercises an existing H2 notification column, rather than only a fresh schema. */
@SpringBootTest
@Transactional
class NotificationSchemaUpgradeTests {
    @Autowired UserRepository users;
    @Autowired NotificationRepository notifications;
    @Autowired NotificationService service;
    @MockitoBean JavaMailSender mail;
    @DynamicPropertySource static void legacySchema(DynamicPropertyRegistry properties) throws Exception {
        String url = "jdbc:h2:mem:notification-upgrade;DB_CLOSE_DELAY=-1;DB_CLOSE_ON_EXIT=FALSE";
        try (var connection = DriverManager.getConnection(url, "sa", ""); var statement = connection.createStatement()) {
            statement.execute("""
                    create table notifications (
                      id bigint generated by default as identity primary key,
                      created_at timestamp(6) with time zone not null,
                      kind enum ('BAND_CONNECTION_REQUEST','BAND_INVITATION','CONCERT_INVITATION','QUOTE_MESSAGE','QUOTE_REQUEST') not null,
                      read_at timestamp(6) with time zone, subject varchar(200) not null,
                      target_url varchar(200) not null, recipient_id bigint not null)
                    """);
        }
        properties.add("spring.datasource.url", () -> url);
    }
    @Test void existingNotificationSchemaAcceptsBothOldAndNewKinds() {
        User actor = account("schema-sender"), recipient = account("schema-recipient");
        service.send(actor, recipient, Notification.Kind.BAND_INVITATION, "Band", "/bands/1");
        service.send(actor, recipient, Notification.Kind.DATE_PROPOSAL, "Band", "/date-proposals/1");
        service.send(actor, recipient, Notification.Kind.DATE_PROPOSAL_RESPONSE, "Band", "/date-proposals/1");
        notifications.flush();
        assertThat(notifications.count()).isEqualTo(3);
    }
    private User account(String name) {
        User user = new User(); user.setUsername(name); user.setFullName(name); user.setEmail(name + "@example.test");
        user.setPasswordHash("unused"); user.setEnabled(true); return users.saveAndFlush(user);
    }
}
