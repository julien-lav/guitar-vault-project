package com.guitarvault;

import java.sql.DriverManager;
import java.time.LocalDate;
import java.time.ZoneOffset;
import java.util.Map;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;
import org.springframework.transaction.annotation.Transactional;
import static org.assertj.core.api.Assertions.assertThat;

@SpringBootTest
@Transactional
class WorkshopJobSchemaUpgradeTests {
    @Autowired UserRepository users;
    @Autowired InstrumentRepository instruments;
    @Autowired LuthierProfileRepository profiles;
    @Autowired LuthierInterventionRepository interventions;
    @Autowired WorkshopJobRepository jobs;
    @Autowired WorkshopJobService service;
    @Autowired jakarta.persistence.EntityManager em;
    @DynamicPropertySource static void oldJobSchema(DynamicPropertyRegistry properties) throws Exception {
        String url = "jdbc:h2:mem:workshop-job-upgrade;DB_CLOSE_DELAY=-1;DB_CLOSE_ON_EXIT=FALSE";
        try (var connection = DriverManager.getConnection(url, "sa", ""); var statement = connection.createStatement()) {
            statement.execute("""
                create table workshop_jobs (
                    id bigint generated by default as identity primary key, activity bigint not null,
                    amount numeric(12,2), currency varchar(3), intervention_id bigint not null unique,
                    scope varchar(3000), stage enum ('APPROVED','CANCELLED','COLLECTED','IN_PROGRESS','QUOTED','QUOTE_DECLINED','READY','RECEIVED') not null,
                    version bigint not null)
                """);
        }
        properties.add("spring.datasource.url", () -> url);
    }
    @Test void existingEnumSchemaAcceptsPausedStagesAndPersistsRevisedTerms() {
        var owner = account("upgrade-owner"); var luthier = account("upgrade-luthier");
        var instrument = instruments.saveAndFlush(new Instrument("Upgrade guitar", "Brand", 2000, owner, "Actif"));
        var workshop = new LuthierProfile(luthier); workshop.update("Workshop", "Paris", "Repairs", "About", "Contact", true); profiles.saveAndFlush(workshop);
        var intervention = interventions.saveAndFlush(new LuthierIntervention(instrument, owner, workshop, LuthierIntervention.Kind.REPAIR, "Repair"));
        service.act(luthier, intervention.getId(), -1, "receive", Map.of("message", "Received"));
        var job = jobs.findByInterventionId(intervention.getId()).orElseThrow();
        service.act(luthier, intervention.getId(), job.getVersion(), "quote", Map.of("amount", "120", "currency", "EUR", "message", "Bridge"));
        service.act(owner, intervention.getId(), job.getVersion(), "approve", Map.of());
        service.act(luthier, intervention.getId(), job.getVersion(), "start", Map.of());
        String completion = LocalDate.now(ZoneOffset.UTC).plusDays(7).toString();
        service.act(luthier, intervention.getId(), job.getVersion(), "request-change", Map.of("amount", "180", "scope", "Bridge and brace", "message", "Discovery", "completionOn", completion));
        em.flush(); em.clear();
        var saved = jobs.findById(job.getId()).orElseThrow();
        assertThat(saved.getStage()).isEqualTo(WorkshopJob.Stage.CHANGE_PENDING);
        assertThat(saved.getAmount()).isEqualByComparingTo("120");
        assertThat(saved.getProposedAmount()).isEqualByComparingTo("180");
        assertThat(saved.getProposedCompletionOn()).isEqualTo(LocalDate.parse(completion));
    }
    private User account(String name) { var user = new User(); user.setUsername(name); user.setEmail(name + "@example.test"); user.setPasswordHash("unused"); return users.saveAndFlush(user); }
}
